#!/usr/bin/env python3
"""Generate the EVA centre-screen cockpit layout (dash_cockpit.json): the baked cockpit photo
(tools/make_cockpit_photo.py) as the background, plus evacanvas live numbers (water/oil/boost, SYNC,
MAGI verdict) positioned over the baked labels. Re-run this rather than editing the json by hand.
Centre screen is native 1280x480 (mgu-render); geometry mirrors make_cockpit_photo.py."""
import json, os

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', 'apps', 'eva_hud', 'hud', 'layouts')

# geometry shared with make_cockpit_photo.py (keep in sync)
W, H = 1280, 480
RX = [432, 720, 1008]   # readout columns
RNUM_Y = 82             # live number row
# SYNC baked label at frame bottom; MAGI verdict block at x=1080
SYNC_X, SYNC_Y = 322, 436
MAGI_X, MAGI_Y = 1080, 320


def txt(i, t, f, x, y, w, h, color='fg', align='left', glow=True, **more):
    p = {'id': i, 'type': 'text', 'text': t, 'font': f, 'x': x, 'y': y, 'w': w, 'h': h, 'align': align, 'color': color}
    if glow:
        p['glow'] = True
    p.update(more)
    return p


def canvas(cid, x, y, w, h, parts):
    return {'id': cid, 'type': 'evacanvas', 'x': x, 'y': y, 'w': w, 'h': h, 'class': 'overlay', 'z': 10, 'parts': parts}


def build():
    bg = {'id': 'bg', 'type': 'evaphoto', 'photo': 'cockpit', 'x': 0, 'y': 0, 'w': W, 'h': H,
          'class': 'ambient', 'z': 0, 'keepInAlert': True}

    # three readout numbers across the top-right, aligned under the baked 水温/油温/増圧 labels
    base = RX[0] - 12
    reads = canvas('cv_reads', base, RNUM_Y, RX[2] - base + 120, 64, [
        txt('water', '{{coolant}}', 'e_num', RX[0] - base, 0, 116, 60),
        txt('oil', '{{oil}}', 'e_num', RX[1] - base, 0, 116, 60),
        txt('boost', '{{boost}}', 'e_num', RX[2] - base, 0, 116, 60),
    ])
    # SYNC value next to the baked "SYNC" label at the frame bottom
    sync = canvas('cv_sync', SYNC_X, SYNC_Y, 90, 30, [
        txt('sync', '{{sync}}%', 'e_num', 0, 0, 90, 30, 'fg', 'left'),
    ])
    # MAGI verdict over the baked "UNANIMOUS" label (bottom-right)
    magi = canvas('cv_magi', MAGI_X, MAGI_Y, 190, 50, [
        txt('verdict', '{{magi:word}}', 'e_speed', 0, 0, 190, 46, 'fg', 'left', True, magiTone='main'),
    ])

    # touch UI (drawn + handled in shared/eva_centre.js): a gear top-right, and a settings panel
    # that opens over the cockpit. Painted by code, not baked; the panel starts hidden.
    gear = {'id': 'uigear', 'type': 'uigear', 'x': 1196, 'y': 36, 'w': 64, 'h': 64, 'class': 'overlay', 'z': 50}
    panel = {'id': 'uipanel', 'type': 'uipanel', 'x': 180, 'y': 50, 'w': 920, 'h': 380, 'class': 'overlay', 'z': 60}

    doc = {'schemaVersion': 2, 'name': 'EVA cockpit (centre)', 'theme': 'eva',
           '_about': 'Generated by tools/cockpit_layout.py (+ make_cockpit_photo.py for the bg). Centre-screen cockpit 1280x480, drawn via mgu-render. Re-run that rather than editing this.',
           'widgets': [bg, reads, sync, magi, gear, panel]}
    os.makedirs(OUT, exist_ok=True)
    with open(os.path.join(OUT, 'dash_cockpit.json'), 'w', encoding='utf-8', newline='\n') as f:
        json.dump(doc, f, ensure_ascii=False, indent=1)
    print('wrote layouts/dash_cockpit.json (centre 1280x480)')


build()
