#!/usr/bin/env python3
"""Generate the EVA centre-screen cockpit layout (dash_cockpit.json): the baked cockpit photo
(tools/make_cockpit_photo.py) as the background, plus evacanvas live numbers (water/oil/boost, SYNC,
MAGI verdict) positioned over the baked labels. Re-run this rather than editing the json by hand.
First pass drawn blind for the iDrive 7 centre screen (mgu-render); iterate positions on the car."""
import json, os

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', 'apps', 'eva_hud', 'hud', 'layouts')


def txt(i, t, f, x, y, w, h, color='fg', align='left', glow=True, **more):
    p = {'id': i, 'type': 'text', 'text': t, 'font': f, 'x': x, 'y': y, 'w': w, 'h': h, 'align': align, 'color': color}
    if glow:
        p['glow'] = True
    p.update(more)
    return p


def canvas(cid, x, y, w, h, parts):
    return {'id': cid, 'type': 'evacanvas', 'x': x, 'y': y, 'w': w, 'h': h, 'class': 'overlay', 'z': 10, 'parts': parts}


def build():
    bg = {'id': 'bg', 'type': 'evaphoto', 'photo': 'cockpit', 'x': 0, 'y': 0, 'w': 1920, 'h': 720,
          'class': 'ambient', 'z': 0, 'keepInAlert': True}

    # right-column readout numbers (labels baked in the photo at x=740, rows 70/220/370)
    reads = canvas('cv_reads', 740, 108, 300, 420, [
        txt('water', '{{coolant}}', 'e_num', 0, 0, 180, 60),
        txt('oil', '{{oil}}', 'e_num', 0, 150, 180, 60),
        txt('boost', '{{boost}}', 'e_num', 0, 300, 180, 60),
    ])
    # SYNC value next to the baked "SYNC" label at the frame bottom
    sync = canvas('cv_sync', 548, 648, 110, 34, [
        txt('sync', '{{sync}}%', 'e_num', 0, 0, 110, 34, 'fg', 'left'),
    ])
    # MAGI verdict over the baked "UNANIMOUS" label (bottom-right)
    magi = canvas('cv_magi', 1420, 494, 420, 60, [
        txt('verdict', '{{magi:word}}', 'e_speed', 0, 0, 420, 56, 'fg', 'left', True, magiTone='main'),
    ])

    doc = {'schemaVersion': 2, 'name': 'EVA cockpit (centre)', 'theme': 'eva',
           '_about': 'Generated by tools/cockpit_layout.py (+ make_cockpit_photo.py for the bg). Centre-screen cockpit, drawn via mgu-render. Re-run that rather than editing this.',
           'widgets': [bg, reads, sync, magi]}
    os.makedirs(OUT, exist_ok=True)
    with open(os.path.join(OUT, 'dash_cockpit.json'), 'w', encoding='utf-8', newline='\n') as f:
        json.dump(doc, f, ensure_ascii=False, indent=1)
    print('wrote layouts/dash_cockpit.json')


build()
