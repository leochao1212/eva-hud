#!/usr/bin/env python3
"""Generate the Shadow dash layouts into apps/shadow_dash.

The photo holds the fade. The drive letter sits in the stock gear window
(x 1196-1424). A black fill covers the kombi status row from y=640.

    python3 -X utf8 tools/shadow_layout.py
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from shadow_geom import BOTTOM_STRIP, layout  # noqa: E402

OUT = os.path.join(HERE, '..', 'apps', 'shadow_dash', 'hud', 'layouts')
MODES = [('sport', 'shadow_sport'), ('comfort', 'shadow_comfort'), ('eco', 'shadow_eco')]


def _part(p):
    one = {k: p[k] for k in p if k != 'quads'}
    if p.get('quads'):
        one['quads'] = p['quads']
    return one


def build(photo, theme):
    spec = layout(photo)
    parts_abs = spec['parts']
    x0 = min(p['x'] for p in parts_abs)
    y0 = min(p['y'] for p in parts_abs)
    x1 = max(p['x'] + p['w'] for p in parts_abs)
    y1 = max(p['y'] + p['h'] for p in parts_abs)
    parts = []
    for p in parts_abs:
        one = _part(p)
        one['x'] = p['x'] - x0
        one['y'] = p['y'] - y0
        parts.append(one)
    gear = dict(spec['gear'])
    sx, sy, sw, sh = BOTTOM_STRIP
    widgets = [
        {'id': 'bg', 'type': 'evaphoto', 'photo': photo, 'x': 0, 'y': 0, 'w': 1920, 'h': 640,
         'class': 'ambient', 'z': 0, 'keepInAlert': True},
        {'id': 'cv', 'type': 'evacanvas', 'x': x0, 'y': y0, 'w': x1 - x0, 'h': y1 - y0,
         'class': 'overlay', 'z': 10, 'parts': parts},
        gear,
        {'id': 'strip', 'type': 'fill', 'x': sx, 'y': sy, 'w': sw, 'h': sh,
         'class': 'overlay', 'z': 30, 'color': 'black', 'keepInAlert': True},
    ]
    return {'schemaVersion': 2, 'name': 'Shadow ' + photo, 'theme': theme,
            '_about': 'Generated by tools/shadow_layout.py. Re-run that rather than editing this.',
            'widgets': widgets}


def main():
    os.makedirs(OUT, exist_ok=True)
    for photo, theme in MODES:
        path = os.path.join(OUT, 'dash_%s.json' % theme)
        with open(path, 'w', encoding='utf-8', newline='\n') as f:
            json.dump(build(photo, theme), f, ensure_ascii=False, indent=1)
            f.write('\n')
        print('wrote', os.path.relpath(path, os.path.join(HERE, '..')))


if __name__ == '__main__':
    main()
