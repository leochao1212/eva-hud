#!/usr/bin/env python3
"""Generate the Shadow dash layouts (one per drive mode): a photo fills the cluster and four
frosted corner panels (baked into the photo) carry white live values with the mode's accent on labels.
Re-run this rather than editing hud/layouts/dash_shadow_*.json by hand."""
import json, os

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', 'apps', 'eva_hud', 'hud', 'layouts')

MODES = [('sport', 'shadow_sport'), ('comfort', 'shadow_comfort'), ('eco', 'shadow_eco')]

# one frosted strip below the meme text (face-free blank zone); matches tools/make_photos.py STRIP
STRIP = (700, 498, 1204, 140)


def txt(i, t, f, x, y, w, h, color, align='left', glow=False):
    p = {'id': i, 'type': 'text', 'text': t, 'font': f, 'x': x, 'y': y, 'w': w, 'h': h, 'align': align, 'color': color}
    if glow:
        p['glow'] = True
    return p


def canvas(cid, box, parts):
    x, y, w, h = box
    return {'id': cid, 'type': 'evacanvas', 'x': x, 'y': y, 'w': w, 'h': h, 'class': 'overlay', 'z': 10, 'parts': parts}


def build(photo, theme):
    # Labels and units are baked into the photo (tools/make_photos.py); only the live numbers are widgets.
    # Part coords are relative to the strip origin (700, 498).
    nums = canvas('cv_nums', STRIP, [
        txt('spd', '{{speed}}', 'e_rpm', 20, 28, 176, 111, 'fg', 'right', True),
        txt('rpm', '{{rpm}}', 'e_num', 352, 42, 158, 57, 'fg', 'right', True),
        txt('gear', '{{gear}}', 'b_gear', 600, 42, 170, 57, 'fg', 'left', True),
        txt('rng', '{{range}}', 'e_num', 798, 42, 126, 57, 'fg', 'right', True),
        txt('wat', '{{coolant}}', 'e_num', 1006, 42, 124, 57, 'fg', 'right', True),
    ])
    bg = {'id': 'bg', 'type': 'evaphoto', 'photo': photo, 'x': 0, 'y': 0, 'w': 1920, 'h': 640,
          'class': 'ambient', 'z': 0, 'keepInAlert': True}
    return {'schemaVersion': 2, 'name': 'Shadow ' + photo, 'theme': theme,
            '_about': 'Generated by tools/shadow_layout.py. Re-run that rather than editing this.',
            'widgets': [bg, nums]}


for photo, theme in MODES:
    out = os.path.join(OUT, 'dash_%s.json' % theme)
    with open(out, 'w', encoding='utf-8', newline='\n') as f:
        json.dump(build(photo, theme), f, ensure_ascii=False, indent=1)
    print('wrote', os.path.relpath(out, os.path.join(HERE, '..')))
